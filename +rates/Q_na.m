function Q = Q_na(V)

  a_11 = 3.802/(0.1027*e^(-(V+2.5)/17.0) + 0.20*e^(-(V+2.5)/150.0));
  a_12 = 3.802/(0.1027*e^(-(V+2.5)/15.0) + 0.23*e^(-(V+2.5)/150.0));
  a_13 = 3.802/(0.1027*e^(-(V+2.5)/12.0) + 0.25*e^(-(V+2.5)/150.0));
  a_2 = inv(0.188495*e^(-(V+7.0)/16.6) + 0.393956);
  a_3 = 7.0e-7*e^(-(V+7.0)/7.7);
  b_11 = 0.1917*e^(-(V+2.5)/20.3);
  b_12 = 0.20*e^(-(V-2.5)/20.3);
  b_13 = 0.22*e^(-(V-7.5)/20.3);
  b_3 = 0.0084 + 0.00002*(V + 7.0);

  a_4 = a_2/1000.0;
  a_5 = a_2/95000;
  b_2 = a_13*a_2*a_3/(b_13*b_3);
  b_4 = a_3;
  b_5 = a_3/50.0;


  %Build Rows
  O = [-(b_13+a_2), a_13, 0, 0, b_2, 0, 0, 0, 0];
  C1 = [b_13, -(b_3+a_13+b_12), a_12, 0, a_3, 0, 0, 0, 0];
  C2 = [0, b_12, -(b_3+a_12+b_11), a_11, 0, 0, 0, a_3, 0];
  C3 = [0, 0, b_11, -(b_3+a_11), 0, 0, 0, 0, a_3];
  IF1 = [a_2, b_3, 0, 0, -(a_4+b_2+a_3+b_12), b_4, 0, a_12, 0];
  I1 = [0, 0, 0, 0, a_4, -(a_5+b_4), b_5, 0, 0];
  I2 = [0, 0, 0, 0, 0, a_5, -(b_5), 0, 0];
  IC2 = [0, 0, b_3, 0, b_12, 0, 0, -(a_12+a_3+b_11), a_11];
  IC3 = [0, 0, 0, b_3, 0, 0, 0, b_11, -(a_11+a_3)];

  %Assemble rows in matrix
  Q = [
  O,
  C1,
  C2,
  C3,
  IF1,
  I1,
  I2,
  IC2,
  IC3
  ];

endfunction
